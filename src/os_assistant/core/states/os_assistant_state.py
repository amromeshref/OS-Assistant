from pydantic import BaseModel, Field
from typing import Literal, Optional

class QueryClassificationState(BaseModel):
    """
    Represents the classification of a user's query, including the enhanced query,
    type, confidence score, reasoning, and follow-up requirements.
    """
    original_query_enhanced: str = Field(..., description="The enhanced version of the user's original query, rewritten for better clarity and understanding.")
    query_type: Literal["command", "information", "both"] = Field(..., description="The type of query.")
    confidence_score: float = Field(..., ge=0, le=1, description="The confidence score of the classification.")
    classification_reasoning: str = Field(..., description="The reasoning behind the classification decision.")
    requires_follow_up: bool = Field(default=False, description="Indicates if a follow-up question is needed for clarification.")
    follow_up_reasoning: Optional[str] = Field(default="", description="The reasoning for why a follow-up question is needed, if applicable.")

class OSAssistantState(BaseModel):
    """
    Represents the state of the OS Assistant, including any relevant information
    about the current session, user preferences, and system status.
    """
    # This may inclue follow-up queries in addition to the original query
    original_query: str = Field(..., description="The original query input by the user.")
    query_classification: QueryClassificationState = Field(default=None, description="The classification of the user's query.")
    # This field should be updated by the parsing logic in the query classification node after receiving the response from the LLM
    # The generated response from the LLM must be in the format of QueryClassificationState, so we can directly assign it to this field
    # If an error occurs, retry and generate another response until we get a valid QueryClassificationState response or reach a maximum number of retries to avoid infinite loops
    query_classification_status: str = Field(default=None, description="The status of the query classification process (e.g., 'pending', 'completed', 'error').")

    # In case the original query requires a follow-up question for clarification
    clarification_attempts: int = Field(default=0, description="The number of attempts made to clarify the original query.")
    generated_response_for_clarification: Optional[str] = Field(default=None, description="The response generated by the LLM for clarification purposes, if applicable. It should be sent to the user to ask for clarification.")