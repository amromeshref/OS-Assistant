class ExecutionOrchestratorState(BaseModel):
    """
    Controls step-by-step execution of the plan.
    Decides what to do next OR whether more information is needed.
    """

    # ===== Execution Progress =====
    next_step: Union[Step, None] = Field(
        default=None,
        description=(
            "The next step to execute. If action_required is True, set this field to the default value. "
            "If is_final_step is True, set this field to the default value. "
            "If action_required is True, set this field to default value."
        ),
    )

    next_step_index: int = Field(
        default=-1,
        description="Index of the next step in the PlanningState. plan_steps list."
    )

    is_final_step: bool = Field(
        default=False,
        description=(
            "Set to True if the next_step is the last step in the plan. "
            "If True, no further steps should be selected afterward."
        ),
    )

    # ===== Dependency Resolution =====
    dependencies_required: bool = Field(
        default=False,
        description=(
            "Indicates whether the next step depends on outputs from previous steps "
            "that must be retrieved before execution."
        ),
    )

    dependency_step_indices: List[int] = Field(
        default_factory=list,
        description=(
            "List of step indices whose outputs are required to execute the next step."
        ),
    )

    dependency_reasoning: str = Field(
        default="",
        description=(
            "Explanation of which dependencies are required and why."
        ),
    )

    # ===== Failure Handling =====
    is_blocked: bool = Field(
        default=False,
        description=(
            "Set to True if a specific step cannot be executed due to missing dependencies "
            "or an unrecoverable error."
        ),
    )

    blocked_reasoning: str = Field(
        default="",
        description=(
            "Explanation of why execution of the blocked step cannot proceed."
        ),
    )

    # next_step_index: int = Field(
    #     default=0,
    #     description=(
    #         "The index of the next step to execute in the plan. "
    #         "This must ONLY be updated if should_proceed is True. "
    #         "If should_proceed is False, this must remain unchanged (default = 0)."
    #     ),
    # )

    # variable_execution_contexts: List[VariableExecutionContext] = Field(
    #     default_factory=list,
    #     description=(
    #       "A list of variable execution contexts that provide details about the output variables of command executions or information retrieval operations. "
    #       "This should be updated after each command execution or information retrieval to include the output variables produced by that step and their current values. If no steps have been executed yet or if the executed steps do not produce any output variables, this should be an empty list."
    #     ),
